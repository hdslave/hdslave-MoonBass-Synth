"""Pack the original Orbital Impact lettering, wire mesh and numerals for native-pixel drawing."""
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parents[1]
atlas = Image.open(root / "art/orbital-impact.png").convert("RGBA")
palette = [0x14111D, 0x20152A, 0x382031, 0x573040, 0x734039, 0x954E34, 0xC65C31, 0xFF7131,
           0xFF8C4F, 0xFFB477, 0x6D6160, 0x9F8E80, 0xCABCAC, 0xE3D7C3, 0xFFF4DB]

def colour_at(x, y):
    r, g, b, a = atlas.getpixel((x, y))
    if a < 20:
        return 0
    background = 0x241D32 if y >= 158 else palette[0]
    rgb = (r, g, b)
    rgb = tuple((u * a + ((background >> s) & 255) * (255 - a)) / 255
                for u, s in zip(rgb, (16, 8, 0)))
    return 1 + min(range(len(palette)), key=lambda n: sum(
        (u - ((palette[n] >> s) & 255)) ** 2 for u, s in zip(rgb, (16, 8, 0))))

lines = ["// Generated by tools/pack_art.py from art/orbital-impact.png.", "#pragma once",
         "#include <cstdint>", "namespace moonbass::art", "{",
         "inline constexpr uint32_t palette[] = { 0, " +
         ", ".join(f"0xff{v:06x}" for v in palette) + " };"]
for name, width, top, height in [("logo", 232, 0, 40), ("moon", 156, 40, 118), ("digits", 208, 158, 24)]:
    lines.append(f"inline constexpr uint8_t {name}[] = {{")
    for y in range(top, top + height):
        row = [colour_at(x, y) << 4 | colour_at(x + 1, y) for x in range(0, width, 2)]
        for at in range(0, len(row), 24):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in row[at:at + 24]) + ",")
    lines.append("};")
lines.append("} // namespace moonbass::art")
(root / "src/ui/orbital_art.h").write_text("\n".join(lines) + "\n")
